/* Assignment Operators :

= : gives value of right operand to left operand , a=5 , 5 is given to a . if a=b=7 then 7 is given to b and then b is given to a .
+= : adds and assignment operator, a+=5; is same as a=a+5; it adds 5 to a and then gives the value to a.
-= : subtracts and assignment operator, a-=5; is same as a=a-5; it subtracts 5 from a and then gives the value to a.
*= : multiplies and assignment operator, a*=5; is same as a=a*5; it multiplies 5 to a and then gives the value to a.
/= : divides and assignment operator, a/=5; is same as a=a/5;   it divides a by 5 and then gives the value to a.


*/

/* MISCELLANEOUS OPERATORS :
 sizeof: Returns the size of variables or data type in bytes.
 sizeof(a) , if a is a integer , it will return the size of integer in bytes on that particular architecture.

 Learn these later better.
 & : Returns the adress of variable, &a , it will return the address of variable a in memory.
 * : Pointer operator , it is used to declare pointer variable and to access the value at the address stored in pointer variable.
 ? : Conditional operator , it is a ternary operator , it takes 3 operands and evaluates the first operand , if it is true then it returns the value of second operand otherwise it returns the value of third operand.


*/

